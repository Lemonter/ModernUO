namespace Server.Items;

/// <summary>
///     Свет, которого нет в ванильном LightType.
///
///     ---- Что такое номер света ----
///
///     На сервере у света нет ни радиуса, ни яркости — только НОМЕР картинки в клиентском
///     light.mul. Круг рисует клиент, и его размер — это размер картинки: один байт на
///     пиксель, значение 0..31. Поэтому «сделать свет дальше» значит завести новую
///     картинку, а не поменять число в коде.
///
///     ---- Откуда клиент берёт номер ----
///
///     Отсюда — только для предмета, ЛЕЖАЩЕГО на земле: номер уходит в пакете 0xF3.
///     Для предмета В РУКЕ клиент берёт номер из тайлдаты (ClassicUO, GameScene.AddLight:
///     <c>light.ID = (byte)it.ItemData.LightIndex</c>). Значит одного этого свойства мало,
///     и тайлдату надо править в паре с ним — иначе фонарь на земле и фонарь в руке светят
///     по-разному. Именно так и было: в тайлдате у фонаря стоял свет 1 (Circle225, 3.6
///     тайла), и в руке он светил ТУСКЛЕЕ факела, хотя тут значилось Circle300.
/// </summary>
public static class MahaonLights
{
    /// <summary>
    ///     Свет фонаря: тот же круг, что у факела, но в пять раз дальше — 1500x1500,
    ///     около 24 тайлов радиуса. Заведён в свободный слот 56 (ванильных записей 56,
    ///     с нуля по 55; всего в lightidx.mul сто мест).
    ///
    ///     Больше экрана, и это намеренно: круг нужен не для красоты, а чтобы при проверке
    ///     теней было видно, как тень ложится через препятствия на всём видимом поле.
    /// </summary>
    public const LightType LanternFar = (LightType)56;
}
